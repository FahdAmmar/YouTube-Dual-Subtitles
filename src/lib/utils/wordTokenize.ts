/**
 * يقسّم نص المقطع إلى رموز (كلمات + مسافات)، محافظاً على المسافات
 * كرموز منفصلة (بفضل مجموعة الالتقاط في split) كي يمكن إعادة تجميع
 * النص الأصلي حرفياً من الرموز — وهو ما يسمح برسم كل كلمة كعنصر منفصل
 * قابل للنقر بينما يبقى التباعد والْتفاف السطر طبيعياً كما لو كان نصاً عادياً
 */
export function tokenizeIntoWords(text: string): string[] {
  return text.split(/(\s+)/).filter((token) => token.length > 0)
}

/** حرف مسافة بحتة بين كلمتين — لا حاجة لرسمه كعنصر قابل للنقر */
export function isWhitespaceToken(token: string): boolean {
  return /^\s+$/.test(token)
}

/**
 * ينزع علامات الترقيم المحيطة بكلمة (فاصلة، نقطة، علامات تنصيص...) قبل
 * البحث عنها في القاموس — النقر على "hello," يجب أن يبحث عن "hello"
 * حرفياً، لا عن الكلمة مع الفاصلة الملتصقة بها. \p{M} (علامات التشكيل
 * التركيبية مثل التنوين العربي) تبقى محفوظة عمداً إلى جانب \p{L}/\p{N}،
 * وإلا لَفقدت كلمات مثل "مرحباً" حركة التنوين الأخيرة بالخطأ
 */
export function stripSurroundingPunctuation(word: string): string {
  return word.replace(/^[^\p{L}\p{N}\p{M}]+|[^\p{L}\p{N}\p{M}]+$/gu, '')
}
