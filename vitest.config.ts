import { defineConfig } from 'vitest/config'
import react from '@vitejs/plugin-react'
import os from 'node:os'
import path from 'node:path'

// Node 25 and newer expose their own `localStorage` on the global object (the Web Storage API is on by default).
// Without a --localstorage-file it is a stub that returns undefined and takes the place of jsdom's real storage,
// so every test that touches localStorage fails with "Cannot read properties of undefined". Turning the Node
// feature off lets jsdom provide it, exactly as on Node 22 and 24. The flag is only passed where it is needed,
// because older Node versions reject options they do not know.
const nodeMajor = Number(process.versions.node.split('.')[0])
const workerArgs = nodeMajor >= 25 ? ['--no-experimental-webstorage'] : []

// availableParallelism() respects CPU affinity and container limits; cpus().length counts every logical processor
const availableCores = os.availableParallelism()

export default defineConfig({
  plugins: [react()],
  resolve: {
    alias: {
      '@': path.resolve(__dirname, './src'),
      // Generated by vite-plugin-pwa during a real build; tests use an inert stand-in
      'virtual:pwa-register/react': path.resolve(__dirname, './src/__tests__/stubs/pwa-register-react.ts'),
    },
  },
  test: {
    environment: 'jsdom',
    globals: true,
    setupFiles: ['./src/__tests__/setup.ts'],
    execArgv: workerArgs,
    // Every test file runs in its own forked process that imports the whole app under jsdom (~300 MB peak, and a
    // CPU-heavy start-up). More workers than the machine can serve at once do not make the run faster; they make it
    // fail in two ways, both seen in practice: (1) timing-sensitive tests starve and time out although each passes
    // alone (reproduced by running 8 workers on 1 core: 3 unrelated tests failed that pass normally), and
    // (2) Vitest gives a fork a fixed 60 s to start (not configurable) and, when it misses that, drops the file from
    // the run ("Failed to start forks worker") instead of failing it, so the totals look green while whole files
    // never ran. Half the logical CPUs, capped at 4 and never below 2, leaves headroom for the OS, the editor and
    // antivirus scanning of node_modules. `VITEST_MAX_WORKERS=<n>` overrides this without editing the file
    maxWorkers: Math.min(4, Math.max(2, Math.floor(availableCores / 2))),
    // Suite cells render full YouTube mock players inside jsdom; under parallel
    // worker pressure on busy machines a few of them exceed the 5s default and
    // flake even though the same test passes in isolation (2s). 15s keeps the
    // suite green without masking real hangs
    testTimeout: 15_000,
  },
})
